import { homedir } from 'node:os';
import { fileURLToPath, pathToFileURL } from 'node:url';
const { chromium } = await import(pathToFileURL(process.env.RECEIPT_PLAYWRIGHT || homedir() + '/.cache/codex-runtimes/codex-primary-runtime/dependencies/node/node_modules/playwright/index.mjs').href);
import fs from 'node:fs/promises';
import assert from 'node:assert/strict';
const root = fileURLToPath(new URL('..', import.meta.url)).replace(/\/$/, '');
const browser = await chromium.launch({headless:true,executablePath:process.env.RECEIPT_CHROMIUM || homedir() + '/Library/Caches/ms-playwright/chromium-1248/chrome-mac-arm64/Google Chrome for Testing.app/Contents/MacOS/Google Chrome for Testing'});
const page = await browser.newPage({viewport:{width:1440,height:1040},deviceScaleFactor:1});
page.setDefaultTimeout(15000);
const errors=[];
page.on('pageerror',e=>errors.push(e.message));
await page.goto('http://127.0.0.1:8765');
await page.waitForFunction(()=>document.querySelector('#nav-total').textContent==='100');
await page.waitForFunction(()=>[...document.querySelectorAll('.receipt-thumbnail')].slice(0,8).every(img=>img.complete&&img.naturalWidth>0));
await fs.mkdir(root+'/output/qa',{recursive:true});
await page.screenshot({path:root+'/output/qa/workspace-desktop.png',fullPage:false});
await page.locator('#filter-merchant').selectOption('Coles');
const count=await page.locator('tbody tr').count();
assert(count>0 && count<100);
await page.locator('#export-format').selectOption('csv');
const downloadPromise=page.waitForEvent('download');
await page.locator('#export-button').click();
const download=await downloadPromise;
await download.saveAs(root+'/output/qa/browser-filtered.csv');
await page.locator('tbody tr').first().click();
await page.locator('#receipt-dialog').waitFor({state:'visible'});
await page.waitForFunction(()=>document.querySelector('#receipt-image').complete&&document.querySelector('#receipt-image').naturalWidth>0);
await page.screenshot({path:root+'/output/qa/receipt-detail.png'});
await page.locator('#close-detail').click();
await page.locator('#search').fill('NO-MATCH-TEST-RECEIPT-XYZ');
assert.equal(await page.locator('tbody tr').count(),0);
assert(await page.locator('#export-button').isDisabled());
await page.locator('#search').fill('');
await page.locator('#filter-merchant').selectOption('');
await page.locator('#advanced-toggle').click();
await page.locator('#filter-missing').selectOption('missing');
const missing=await page.locator('tbody tr').count();
assert.equal(missing,0,'Validated sample set must not have missing core fields');
await page.locator('#filter-missing').selectOption('');
await page.locator('#advanced-toggle').click();
await page.setViewportSize({width:390,height:844});
await page.screenshot({path:root+'/output/qa/workspace-mobile.png',fullPage:false});
const widths=await page.evaluate(()=>({window:innerWidth,document:document.documentElement.scrollWidth}));
assert(widths.document<=widths.window,`mobile horizontal overflow ${JSON.stringify(widths)}`);
await page.setViewportSize({width:1440,height:1040});
await page.locator('#nav-report').click();
await page.waitForFunction(()=>document.querySelector('#report-engine').textContent.includes('AI'));
await page.screenshot({path:root+'/output/qa/analysis-report.png',fullPage:true});
await page.goto('http://127.0.0.1:8765/output/quality/index.html');
assert.equal(await page.locator('#validation100 .receipt').count(),100);
assert.equal(await page.locator('#validation100 .badge.pass').count(),100);
assert.equal(await page.locator('#original100 .receipt').count(),100);
await page.locator('#validation100 input').fill('au_full_021');
await page.locator('#validation100 .receipt:not([hidden]) > summary').click();
await page.screenshot({path:root+'/output/qa/quality-validation100.png',fullPage:false});
for (const path of ['/research/validation100_manifest.json','/research/validation100_reference_changes.json','/research/evaluations/validation100/evaluation.json']) {
  assert.equal((await page.request.get('http://127.0.0.1:8765'+path)).status(),200);
}
assert.deepEqual(errors,[]);
await fs.writeFile(root+'/output/qa/browser-check.json',JSON.stringify({passed:true,merchant_filter_count:count,missing_fields_filter_count:missing,validation_passed:100,original_preserved:100,mobile_width:widths,js_errors:errors},null,2));
console.log(JSON.stringify({passed:true,merchant_filter_count:count,missing_fields_filter_count:missing,js_errors:errors}));
await browser.close();
